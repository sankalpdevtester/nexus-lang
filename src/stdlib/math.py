import math

def sin(x):
    """
    Compute the sine of x.
    
    Args:
        x (float): The input angle in radians.
    
    Returns:
        float: The sine of x.
    """
    return math.sin(x)

def cos(x):
    """
    Compute the cosine of x.
    
    Args:
        x (float): The input angle in radians.
    
    Returns:
        float: The cosine of x.
    """
    return math.cos(x)

def tan(x):
    """
    Compute the tangent of x.
    
    Args:
        x (float): The input angle in radians.
    
    Returns:
        float: The tangent of x.
    """
    return math.tan(x)

def sqrt(x):
    """
    Compute the square root of x.
    
    Args:
        x (float): The input number.
    
    Returns:
        float: The square root of x.
    """
    return math.sqrt(x)

def pow(x, y):
    """
    Compute x to the power of y.
    
    Args:
        x (float): The base number.
        y (float): The exponent.
    
    Returns:
        float: x to the power of y.
    """
    return math.pow(x, y)

def log(x):
    """
    Compute the natural logarithm of x.
    
    Args:
        x (float): The input number.
    
    Returns:
        float: The natural logarithm of x.
    """
    return math.log(x)

def exp(x):
    """
    Compute the exponential of x.
    
    Args:
        x (float): The input number.
    
    Returns:
        float: The exponential of x.
    """
    return math.exp(x)

def abs(x):
    """
    Compute the absolute value of x.
    
    Args:
        x (float): The input number.
    
    Returns:
        float: The absolute value of x.
    """
    return abs(x)

def max(*args):
    """
    Compute the maximum of the input numbers.
    
    Args:
        *args (float): The input numbers.
    
    Returns:
        float: The maximum of the input numbers.
    """
    return max(*args)

def min(*args):
    """
    Compute the minimum of the input numbers.
    
    Args:
        *args (float): The input numbers.
    
    Returns:
        float: The minimum of the input numbers.
    """
    return min(*args)